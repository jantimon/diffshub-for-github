/**
 * Writes `public/THIRD-PARTY-NOTICES.txt`, which ships in the extension: every
 * production dependency with its licence and NOTICE files, as pnpm lists them.
 *
 * Generated rather than written by hand, so a new dependency cannot be left
 * out. It lists everything installed for production, which is at least what
 * the bundle contains.
 */

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const target = path.join(root, 'public', 'THIRD-PARTY-NOTICES.txt');

const listed = JSON.parse(
  execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], { cwd: root, encoding: 'utf8' }),
);

/** The files a licence asks to be passed on */
const LEGAL = /^(licen[cs]e|copying|notice)(\.|$)/i;

const packages = Object.values(listed)
  .flat()
  .toSorted((a, b) => a.name.localeCompare(b.name));

const sections = packages.map((pkg) => {
  const dir = pkg.paths[0];
  const files = fs
    .readdirSync(dir)
    .filter((file) => LEGAL.test(file))
    .toSorted();
  const texts = files.map((file) => fs.readFileSync(path.join(dir, file), 'utf8').trim());
  const head = `${pkg.name} ${pkg.versions.join(', ')} (${pkg.license})`;
  const body =
    texts.length > 0 ? texts.join('\n\n') : `No licence file in the package. ${pkg.homepage ?? ''}`;
  return `${head}\n${'-'.repeat(head.length)}\n\n${body}`;
});

fs.writeFileSync(
  target,
  `DiffsHub for GitHub is MIT licensed. It bundles the packages below, which
carry their own terms. This file is generated by scripts/notices.mjs.

${sections.join('\n\n\n')}
`,
);
console.log(`notices: ${packages.length} packages -> ${path.relative(root, target)}`);
